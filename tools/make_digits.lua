-- make the list of the decimal digits zero (General_Category Nd) from
-- UnicodeData.txt, used for numeric collation (ICU's DIGIT_TAG): the digits
-- of a decimal system are consecutive code points from zero to nine
local dir = arg[1] or "data"

local zeros, zero = {}, nil
for line in io.lines(dir .. "/UnicodeData.txt") do
  local codepoint, value = line:match("^(%x+);[^;]*;Nd;[^;]*;[^;]*;[^;]*;(%d);")
  if codepoint then
    codepoint, value = tonumber(codepoint, 16), tonumber(value)
    if value == 0 then
      zero = codepoint
      zeros[#zeros + 1] = codepoint
    elseif not zero or codepoint - zero ~= value then
      error(string.format("U+%04X: the digits are not consecutive", codepoint))
    end
  end
end

local out = {}
for i, codepoint in ipairs(zeros) do
  out[#out + 1] = string.format("0x%X,", codepoint)
  if i % 8 == 0 then out[#out + 1] = "\n  " else out[#out + 1] = " " end
end

print("-- generated by tools/make_digits.lua")
print("-- the decimal digits zero; the digits one to nine follow each of them")
print("return {")
print("  " .. (table.concat(out):gsub("%s*$", "")))
print("}")
