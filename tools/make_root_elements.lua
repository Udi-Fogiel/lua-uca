-- the weights in use in the root collation, for the tailoring builder
-- run: texlua tools/make_root_elements.lua > src/lua-uca/lua-uca-root-elements.lua
local builder = dofile("src/lua-uca/lua-uca-builder.lua")
local root = dofile("src/lua-uca/lua-uca-root.lua")
local info = dofile("src/lua-uca/lua-uca-root-info.lua")
local data = builder.collect_root_elements(root, info)

local function list(t) return "{" .. table.concat(t, ",") .. "}" end

local primaries = {}
for p in pairs(data.sec_ter) do primaries[#primaries + 1] = p end
table.sort(primaries)

print("-- generated by tools/make_root_elements.lua from FractionalUCA.txt (UCA " .. info.version .. ")")
print("return {")
print("primaries=" .. list(data.primaries) .. ",")
print("secondary_ces=" .. list(data.secondary_ces) .. ",")
print("tertiary_ces=" .. list(data.tertiary_ces) .. ",")
print("sec_ter={")
for _, p in ipairs(primaries) do print("[" .. p .. "]=" .. list(data.sec_ter[p]) .. ",") end
print("}}")
